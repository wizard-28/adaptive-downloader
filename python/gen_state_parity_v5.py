def build():
    spec = default_state_spec()
    return {
        "label": "Python<->Go v5 state parity fixture (generated by python/gen_state_parity_v5.py)",
        "tolerance": TOLERANCE,
        "state_spec": spec.to_json(),
        "feature_names": list(FEATURE_NAMES),
        "cases": [
            {"name": n, "observation": o, "features": features(o, spec)}
            for n, o in CASES.items()
        ],
    }


if __name__ == "__main__":
    doc = json.dumps(build(), indent=2) + "\n"
    if "--check" in sys.argv:
        cur = open(OUT).read()
        if cur != doc:
            sys.exit("state_parity_v5.json is stale; regenerate")
        print("parity fixture up to date")
    else:
        with open(OUT, "w") as f:
            f.write(doc)
        print("wrote", os.path.normpath(OUT))
