package server

import (
	"context"
	"errors"
	"fmt"
	"net/http"
	"time"
)

// ErrInvalidLogicalSize indicates a non-positive logical object size.
var ErrInvalidLogicalSize = errors.New("server: invalid logical size")

// DefaultLogicalSize is the recommended logical object size for Stage 0
// full-trace Mahimahi replays. 16 TiB is a safety envelope, not a performance
// choice: the longest native traces are ~82 minutes (~4920 s), so even an
// absurd sustained 2 GiB/s replay for two hours would consume ~14.1 TiB and
// still not exhaust the object. The eventual harness may pass any explicit
// size to NewLogical.
const DefaultLogicalSize int64 = 1 << 44 // 16 TiB

// logicalChunkSize is the generation and write granularity for logical
// content. It matches the pacing granularity used by writeThrottled (16 KiB),
// so both content sources are served with the same application-level pacing
// behavior, and it bounds per-request memory regardless of the requested
// range length.
const logicalChunkSize = 16 << 10

// logicalContent is a deterministic, generated byte object that is never
// materialized in memory. Any inclusive range can be generated on demand.
type logicalContent struct {
	n int64
}

func (l logicalContent) size() int64 { return l.n }

// write streams the inclusive range [start, end] in bounded-size chunks,
// applying the same application-level pacing as writeThrottled (sleep
// proportional to chunk size / rate before each 16 KiB chunk).
func (l logicalContent) write(ctx context.Context, w http.ResponseWriter, start, end int64, rate int64) bool {
	buf := make([]byte, logicalChunkSize)
	for off := start; off <= end; {
		n := int64(len(buf))
		if remaining := end - off + 1; n > remaining {
			n = remaining
		}
		if rate > 0 {
			d := time.Duration(float64(n) / float64(rate) * float64(time.Second))
			if !sleepContext(ctx, d) {
				return false
			}
		}
		fillLogical(buf[:n], off)
		if _, err := w.Write(buf[:n]); err != nil {
			return false
		}
		off += n
	}
	return true
}

// NewLogical returns a Server backed by a deterministic generated logical
// object of exactly size bytes. The object is never allocated: every range is
// generated on demand, so memory use is independent of size, and the same
// absolute byte offset always yields the same byte. HTTP Range semantics,
// Content-Length, Content-Range, delays, pacing, failure injection, request
// logging, and stats behave exactly as for New(content []byte); only the body
// source differs.
//
// It returns ErrInvalidLogicalSize when size <= 0.
func NewLogical(size int64) (*Server, error) {
	if size <= 0 {
		return nil, fmt.Errorf("%w: must be > 0, got %d", ErrInvalidLogicalSize, size)
	}
	return newServer(logicalContent{n: size}), nil
}

// logicalSeed fixes the generated content. Changing it changes every byte of
// every logical object, so it is a package constant, not configuration.
const logicalSeed uint64 = 0x9E3779B97F4A7C15

// mixLogicalWord maps an 8-byte word index to a deterministic 64-bit value
// using the splitmix64 finalizer. It is a content generator, not a
// cryptographic primitive.
func mixLogicalWord(word uint64) uint64 {
	z := word*0x9E3779B97F4A7C15 + logicalSeed
	z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9
	z = (z ^ (z >> 27)) * 0x94D049BB133111EB
	return z ^ (z >> 31)
}

// fillLogical fills dst with the deterministic content starting at absolute
// offset off. Each byte depends only on its absolute offset (via its 8-byte
// word index and byte position within the word), so arbitrary ranges can be
// generated directly without generating the prefix, and a byte is identical no
// matter how reads are grouped or aligned.
func fillLogical(dst []byte, off int64) {
	for len(dst) > 0 {
		z := mixLogicalWord(uint64(off >> 3))
		shift := uint(off&7) * 8
		n := 8 - int(off&7)
		if n > len(dst) {
			n = len(dst)
		}
		for i := 0; i < n; i++ {
			dst[i] = byte(z >> (shift + uint(i)*8))
		}
		dst = dst[n:]
		off += int64(n)
	}
}
